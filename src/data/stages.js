//
// waypoints  : 적이 지나는 경로. 타일 좌표 [col, row], 축 정렬만 허용.
//              맵 밖에서 시작해 맵 밖으로 나간다.
// platforms  : 타워를 놓을 수 있는 잔디 구역. [c0, r0, c1, r1] (양끝 포함).
