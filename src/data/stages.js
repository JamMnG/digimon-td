//              platforms를 생략하면 경로 밖 전체가 배치 가능해진다.
// scale      : 이 스테이지 전용 적 배율. 맵 난이도를 수치가 아니라 지형과 함께 조절한다.
// start      : 시작 자원 덮어쓰기 (생략 시 balance.js 기본값)
// unlock     : { stage, wave } — 해당 스테이지에서 그 웨이브까지 도달해야 열린다.
//              클리어 전체를 요구하면 프로토타입 단계에서 뒷맵을 아무도 못 보게 된다.
